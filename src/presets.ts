export function instantiatePreset(preset: GuidePreset): GuideStep[] {
  return preset.steps.map((step, index) => ({
    id: uid(),
    title: step.title,
    instruction: step.instruction,
    status: index === 0 ? "active" : "pending",
    paragraphRefs: [],
  }));
}
